"""
Generate the date-token tables the API's Hevy CSV importer reads.

Reads:
  - ../content/imports/hevy/dates.json: the month tokens the Hevy app and
    hevy.com write in their export dates, per language, and the day-period
    words hevy.com puts next to a 12-hour time, copied from real exports

Writes:
  - ../api/lib/models/hevy_dates.dart: two const maps, formatted

The app writes `d MMM yyyy, HH:mm` with the month in the app's language;
hevy.com writes `Intl`'s medium date and short time in the site's language,
with an abbreviated month in some, a day period (`PM`, `오후`, `下午`) in
others. No month token means two different months in any pair of languages,
and no day-period word is both a morning and an afternoon one (both asserted
here), so one table of each reads every language without detecting which.
Re-run after editing the JSON:

    uv run scripts/hevy_dates.py
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATES = ROOT / 'content' / 'imports' / 'hevy' / 'dates.json'
OUT = ROOT / 'api' / 'lib' / 'models' / 'hevy_dates.dart'


def token_key(token: str) -> str:
    """The form a token is looked up in: case-folded, no trailing dot."""
    return token.lower().rstrip('.')


def months(by_exporter: dict[str, dict[str, list[str]]]) -> dict[str, int]:
    table: dict[str, int] = {}
    for exporter, languages in by_exporter.items():
        for lang, tokens in languages.items():
            assert len(tokens) == 12, f'{exporter} {lang}: {len(tokens)} month tokens'
            for i, token in enumerate(tokens, start=1):
                key = token_key(token)
                assert table.get(key, i) == i, f'{key!r} is month {table[key]} and {i}'
                table[key] = i
    return dict(sorted(table.items()))


def day_periods(by_half: dict[str, list[str]]) -> dict[str, int]:
    """Day-period word → the hours it adds to a 12-hour clock: 0 before noon, 12 after."""
    table: dict[str, int] = {}
    for half, words in by_half.items():
        hours = {'am': 0, 'pm': 12}[half]
        for word in words:
            key = token_key(word)
            assert table.get(key, hours) == hours, f'{key!r} is both am and pm'
            table[key] = hours
    return dict(sorted(table.items()))


def dart_string(s: str) -> str:
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def main() -> None:
    data = json.loads(DATES.read_text())
    month_table = months(data['months'])
    period_table = day_periods(data['dayPeriods'])
    lines = [
        '// Generated by scripts/hevy_dates.py from content/imports/hevy/dates.json — do not edit.',
        '',
        "/// A month token as Hevy's app or hevy.com writes it in an export date, in",
        '/// any of their languages (case-folded, trailing dot dropped) → month number.',
        '/// One table serves every language: no token means two different months',
        '/// anywhere.',
        'const hevyMonths = <String, int>{',
        *(f'  {dart_string(k)}: {v},' for k, v in month_table.items()),
        '};',
        '',
        '/// A day-period word as hevy.com writes it next to a 12-hour time, in any of',
        '/// its languages (case-folded) → the hours it adds to the clock: 0 for a',
        '/// morning word, 12 for the rest. No word is both.',
        'const hevyDayPeriods = <String, int>{',
        *(f'  {dart_string(k)}: {v},' for k, v in period_table.items()),
        '};',
        '',
    ]
    OUT.write_text('\n'.join(lines))
    subprocess.run(['dart', 'format', str(OUT)], check=True, capture_output=True)
    print(f'{len(month_table)} month tokens, {len(period_table)} day periods → {OUT}')


if __name__ == '__main__':
    main()
