/// Compiles each MCP Apps card script in `cards/` with dart2js and writes
/// them into the API as string constants, `api/lib/mcp/widgets/cards.g.dart`
/// (gitignored): the Lambda zip carries only the compiled binary, so a page's
/// script has to be inside it.
///
///   dart run tool/emit_cards.dart        (or `make cards` from the repo root)
///
/// `cards/<name>.dart` becomes `_<name>CardJs`, inlined by the page in
/// `api/lib/mcp/widgets/<name>.dart`.
library;

import 'dart:io';

final _api = File('../api/lib/mcp/widgets/cards.g.dart');

Future<void> main() async {
  final scripts = Directory('cards').listSync().whereType<File>().where((f) => f.path.endsWith('.dart')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final out = Directory('build/cards')..createSync(recursive: true);

  final constants = StringBuffer();
  for (final script in scripts) {
    final name = script.uri.pathSegments.last.replaceAll('.dart', '');
    final js = '${out.path}/$name.js';
    // -O4 is safe here: the cards read results through patterns, never casts,
    // so the checks it drops are ones the code doesn't rely on.
    final compile = await Process.run('dart', ['compile', 'js', '-O4', '--no-source-maps', '-o', js, script.path]);
    if (compile.exitCode != 0) {
      stderr
        ..write(compile.stdout)
        ..write(compile.stderr);
      exit(compile.exitCode);
    }
    final source = File(js).readAsStringSync();
    constants
      ..writeln()
      ..writeln('/// `pages/cards/$name.dart`, compiled by dart2js -O4 (${source.length} bytes).')
      ..writeln('const _${name.toCamelCase()}CardJs = ${source.toDartLiteral()};');
    stdout.writeln('$name: ${source.length} bytes');
  }

  _api.writeAsStringSync(
    '// GENERATED by `make cards` (pages/tool/emit_cards.dart) from pages/cards/. Do not edit.\n'
    '// ignore_for_file: type=lint\n'
    '\n'
    "part of '../widgets.dart';\n"
    '$constants',
  );
  stdout.writeln('wrote ${_api.path}');
}

extension on String {
  /// `exercise_progress` → `exerciseProgress`.
  String toCamelCase() => splitMapJoin(
    RegExp(r'_([a-z])'),
    onMatch: (m) => m[1]!.toUpperCase(),
    onNonMatch: (s) => s,
  );

  /// A single-quoted Dart literal. `</script` is broken up because the page
  /// inlines this into a <script> element, which the first one would close;
  /// `<\/` means the same inside a JS string or regex.
  String toDartLiteral() {
    final escaped = replaceAll(r'\', r'\\')
        .replaceAll("'", r"\'")
        .replaceAll(r'$', r'\$')
        .replaceAll('\n', r'\n')
        .replaceAll('\r', r'\r')
        .replaceAll('</script', r'<\\/script');
    return "'$escaped'";
  }
}
