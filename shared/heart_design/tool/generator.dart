import 'dart:convert';

/// The eleven tokens of a palette, in the order every output lists them.
const tokenNames = [
  'ground',
  'surface',
  'fill',
  'ink',
  'muted',
  'faint',
  'border',
  'accent',
  'onAccent',
  'accentInk',
  'destructive',
];

/// Every file `tokens.json` generates, by its path from the package root,
/// with its contents. `make design` writes them; the tests check they are
/// current.
Map<String, String> outputs(String tokensJson) {
  final design = Design.parse(tokensJson);
  return {
    'lib/src/presets.g.dart': design.toDart(),
    '../../site/assets/tokens.css': design.toCss(),
  };
}

final class Design {
  final String fallback;
  final int controlRadius;
  final int cardRadius;

  /// Each face's generic family, `serif` or `sans-serif`.
  final Map<String, String> faces;
  final List<PresetSpec> presets;

  const new({
    required this.fallback,
    required this.controlRadius,
    required this.cardRadius,
    required this.faces,
    required this.presets,
  });

  factory parse(String source) {
    final design = switch (jsonDecode(source)) {
      {
        'default': final String fallback,
        'radii': {'control': final int control, 'card': final int card},
        'faces': final Map<String, dynamic> faces,
        'presets': final Map<String, dynamic> presets,
      } =>
        Design(
          fallback: fallback,
          controlRadius: control,
          cardRadius: card,
          faces: {for (final MapEntry(:key, :value) in faces.entries) key: _family(key, value)},
          presets: [for (final MapEntry(:key, :value) in presets.entries) PresetSpec.parse(key, value)],
        ),
      _ => throw const FormatException('tokens.json is not {default, radii: {control, card}, faces, presets}'),
    };
    design._check();
    return design;
  }

  static String _family(String face, Object? family) {
    return switch (family) {
      'serif' || 'sans-serif' => family as String,
      _ => throw FormatException('tokens.json: face $face is "$family", not serif or sans-serif'),
    };
  }

  void _check() {
    if (!presets.any((preset) => preset.name == fallback)) {
      throw FormatException('tokens.json: the default, $fallback, is not a preset');
    }
    for (final preset in presets) {
      for (final face in [preset.text, preset.title, preset.display]) {
        if (!faces.containsKey(face)) throw FormatException('tokens.json: ${preset.name} uses $face, not in faces');
      }
    }
  }

  /// The default preset first: CSS needs it so a later preset's rule of the
  /// same specificity wins over the bare `:root` one, and the artifact so the
  /// other themes inherit from the house style.
  List<PresetSpec> get defaultFirst {
    return [
      ...presets.where((preset) => preset.name == fallback),
      ...presets.where((preset) => preset.name != fallback),
    ];
  }

  String toDart() {
    final out = StringBuffer()
      ..writeln('// Generated by tool/generate.dart from tokens.json: edit that and run `make design`.')
      ..writeln()
      ..writeln("import 'palette.dart';")
      ..writeln()
      ..writeln('/// Buttons, inputs, chips: every control.')
      ..writeln('const controlRadius = $controlRadius.0;')
      ..writeln()
      ..writeln('/// Cards, sheets, dialogs. No pills anywhere.')
      ..writeln('const cardRadius = $cardRadius.0;')
      ..writeln()
      ..writeln('/// A theme preset: one identity worn by both brightnesses.')
      ..writeln('///')
      ..writeln('/// The name is the stored identifier; display names are copy and live in')
      ..writeln('/// the translations.')
      ..writeln('enum Preset {');
    for (final (i, preset) in presets.indexed) {
      for (final line in _wrap(preset.note, 76)) {
        out.writeln('  /// $line');
      }
      out
        ..writeln('  ${preset.name}(')
        ..writeln('    light: ${_palette(preset.light)},')
        ..writeln('    dark: ${_palette(preset.dark)},')
        ..writeln("    textFont: '${preset.text}',")
        ..writeln("    titleFont: '${preset.title}',")
        ..writeln("    displayFont: '${preset.display}',")
        ..writeln('    headlineSize: ${preset.headlineSize},')
        ..writeln('    headlineWeight: ${preset.headlineWeight},')
        ..writeln('  )${i == presets.length - 1 ? ';' : ','}');
    }
    out
      ..writeln()
      ..writeln('  final Palette light;')
      ..writeln('  final Palette dark;')
      ..writeln()
      ..writeln('  /// Everything that reads: body, labels, controls.')
      ..writeln('  final String textFont;')
      ..writeln()
      ..writeln('  /// Page and dialog titles, where a preset may hand headlines to a second')
      ..writeln('  /// face without shouting everywhere [displayFont] does.')
      ..writeln('  final String titleFont;')
      ..writeln()
      ..writeln('  /// Headlines and numbers worth a shout, nothing else.')
      ..writeln('  final String displayFont;')
      ..writeln()
      ..writeln('  /// The page title, tuned per display face: different faces fill the same')
      ..writeln('  /// box very differently at one size. The weight is CSS-style, 100 to 900.')
      ..writeln('  final double headlineSize;')
      ..writeln('  final int headlineWeight;')
      ..writeln()
      ..writeln('  new({')
      ..writeln('    required this.light,')
      ..writeln('    required this.dark,')
      ..writeln('    required this.textFont,')
      ..writeln('    required this.titleFont,')
      ..writeln('    required this.displayFont,')
      ..writeln('    required this.headlineSize,')
      ..writeln('    required this.headlineWeight,')
      ..writeln('  });')
      ..writeln()
      ..writeln('  /// The house style: a first launch, and a stored name this build does not')
      ..writeln('  /// know.')
      ..writeln('  static const fallback = Preset.$fallback;')
      ..writeln('}')
      ..writeln()
      ..writeln('/// The presets as CSS custom properties, as `site/assets/tokens.css` has')
      ..writeln('/// them, for a page that inlines its styles.')
      ..writeln("const tokensCss = r'''")
      ..write(toCss())
      ..writeln("''';");
    return out.toString();
  }

  static String _palette(Map<String, String> palette) {
    final out = StringBuffer('Palette(\n');
    for (final name in tokenNames) {
      out.writeln('      $name: 0xFF${palette[name]!.substring(1)},');
    }
    return (out..write('    )')).toString();
  }

  String toCss() {
    final order = defaultFirst;
    final out = StringBuffer()
      ..writeln('/* Generated by shared/heart_design from tokens.json: edit that and run `make design`.')
      ..writeln()
      ..writeln(
        '   ${titleCase(fallback)} is the default. An element picks a preset with '
        'data-preset="${presets.map((preset) => preset.name).join('|')}"',
      )
      ..writeln('   and follows the OS brightness unless data-theme="light|dark" pins it, on :root or on the')
      ..writeln('   element that carries data-preset. --on-destructive is derived: the surface in light,')
      ..writeln('   onAccent in dark. */')
      ..writeln()
      ..writeln(':root {')
      ..writeln('  --radius-control: ${controlRadius}px;')
      ..writeln('  --radius-card: ${cardRadius}px;')
      ..writeln('}');
    for (final preset in order) {
      out
        ..writeln()
        ..writeln('${_selectors(preset, root: ':root', preset: '')} {')
        ..write(_declarations(preset.light, dark: false))
        ..writeln('  --font-text: ${fontStack(preset.text)};')
        ..writeln('  --font-title: ${fontStack(preset.title)};')
        ..writeln('  --font-display: ${fontStack(preset.display)};')
        ..writeln('  --headline-size: ${preset.headlineSize}px;')
        ..writeln('  --headline-weight: ${preset.headlineWeight};')
        ..writeln('  color-scheme: light;')
        ..writeln('}');
    }
    out
      ..writeln()
      ..writeln('@media (prefers-color-scheme: dark) {');
    for (final (i, preset) in order.indexed) {
      if (i > 0) out.writeln();
      final selectors = _selectors(
        preset,
        root: ':root:not([data-theme="light"])',
        preset: ':not([data-theme="light"])',
      );
      out
        ..writeln('  ${selectors.replaceAll('\n', '\n  ')} {')
        ..write(_declarations(preset.dark, dark: true, indent: '    '))
        ..writeln('    color-scheme: dark;')
        ..writeln('  }');
    }
    out.writeln('}');
    for (final preset in order) {
      out
        ..writeln()
        ..writeln('${_selectors(preset, root: ':root[data-theme="dark"]', preset: '[data-theme="dark"]')} {')
        ..write(_declarations(preset.dark, dark: true))
        ..writeln('  color-scheme: dark;')
        ..writeln('}');
    }
    return out.toString();
  }

  /// The selectors a preset's rule applies to: the default preset's also
  /// match the bare [root].
  String _selectors(PresetSpec spec, {required String root, required String preset}) {
    final own = '[data-preset="${spec.name}"]$preset';
    return spec.name == fallback ? '$root,\n$own' : own;
  }

  static String _declarations(Map<String, String> palette, {required bool dark, String indent = '  '}) {
    final out = StringBuffer();
    for (final name in tokenNames) {
      out.writeln('$indent--${kebab(name)}: ${palette[name]};');
    }
    final onDestructive = dark ? palette['onAccent'] : palette['surface'];
    return (out..writeln('$indent--on-destructive: $onDestructive;')).toString();
  }

  /// [face] with its fallbacks, as CSS.
  String fontStack(String face) {
    return switch (faces[face]) {
      'serif' => "'$face', Georgia, serif",
      _ => "'$face', system-ui, -apple-system, 'Segoe UI', sans-serif",
    };
  }
}

final class PresetSpec {
  final String name;
  final String note;
  final String text;
  final String title;
  final String display;
  final int headlineSize;
  final int headlineWeight;
  final Map<String, String> light;
  final Map<String, String> dark;

  const new({
    required this.name,
    required this.note,
    required this.text,
    required this.title,
    required this.display,
    required this.headlineSize,
    required this.headlineWeight,
    required this.light,
    required this.dark,
  });

  factory parse(String name, Object? json) {
    return switch (json) {
      {
        'note': final String note,
        'fonts': {'text': final String text, 'title': final String title, 'display': final String display},
        'headline': {'size': final int size, 'weight': final int weight},
        'light': final Map<String, dynamic> light,
        'dark': final Map<String, dynamic> dark,
      } =>
        PresetSpec(
          name: name,
          note: note,
          text: text,
          title: title,
          display: display,
          headlineSize: size,
          headlineWeight: weight,
          light: _palette('$name.light', light),
          dark: _palette('$name.dark', dark),
        ),
      _ => throw FormatException('tokens.json: preset $name is not {note, fonts, headline, light, dark}'),
    };
  }

  static final _hex = RegExp(r'^#[0-9A-F]{6}$');

  static Map<String, String> _palette(String where, Map<String, dynamic> json) {
    final unknown = json.keys.where((key) => !tokenNames.contains(key));
    if (unknown.isNotEmpty) throw FormatException('tokens.json: $where has ${unknown.join(', ')}, not a token');
    return {
      for (final name in tokenNames)
        name: switch (json[name]) {
          final String hex when _hex.hasMatch(hex) => hex,
          null => throw FormatException('tokens.json: $where has no $name'),
          final other => throw FormatException('tokens.json: $where.$name is $other, not #RRGGBB in upper case'),
        },
    };
  }
}

String kebab(String camel) => camel.replaceAllMapped(RegExp('[A-Z]'), (m) => '-${m[0]!.toLowerCase()}');

String titleCase(String word) => '${word[0].toUpperCase()}${word.substring(1)}';

/// [text] in lines of at most [width] characters, broken between words.
List<String> _wrap(String text, int width) {
  final lines = <String>[];
  var line = StringBuffer();
  for (final word in text.split(' ')) {
    if (line.isNotEmpty && line.length + 1 + word.length > width) {
      lines.add(line.toString());
      line = StringBuffer();
    }
    if (line.isNotEmpty) line.write(' ');
    line.write(word);
  }
  return lines..add(line.toString());
}
